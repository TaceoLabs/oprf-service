use ark_ff::UniformRand;
use rand::SeedableRng as _;

use super::*;
use crate::legendre::{commit_key, proof::batched_scalar};

fn sample(
    n_bits: usize,
    seed: u64,
) -> (
    LegendreParams,
    Affine,
    ScalarField,
    Vec<bool>,
    LegendreProof,
) {
    let mut rng = rand_chacha::ChaCha12Rng::seed_from_u64(seed);
    let params = LegendreParams::new(n_bits);
    let (k, rho, h) = (
        ScalarField::rand(&mut rng),
        ScalarField::rand(&mut rng),
        ScalarField::rand(&mut rng),
    );
    let c_k = commit_key(&params, k, rho);
    let (bits, proof) = LegendreProof::prove(&params, k, rho, h, &mut rng).expect("non-zero");
    (params, c_k, h, bits, proof)
}

#[test]
fn hints_satisfy_the_circuit_constraints() {
    for (n_bits, seed) in [(128, 1), (128, 2), (16, 3), (40, 4)] {
        let (params, c_k, h, bits, proof) = sample(n_bits, seed);
        let hints = CircuitHints::new(&params, c_k, h, &bits, &proof);
        check_hints(&params, c_k, h, &bits, &proof, &hints).expect("constraints hold");

        // the reduced value is the scalar the native verifier uses
        let batch = batch_challenges(c_k, proof.c_sigma, h, &bits);
        let s = batched_scalar(
            &batch.gammas(n_bits),
            &proof.z,
            proof.z_k,
            proof.e,
            h,
            &bits,
        );
        assert_eq!(hints.s, to_int(s));
        assert_eq!(hints.xi, to_int(proof.z_k + proof.e * h));
    }
}

#[test]
fn wrong_hints_violate_the_circuit_constraints() {
    let (params, c_k, h, bits, proof) = sample(128, 5);
    let hints = CircuitHints::new(&params, c_k, h, &bits, &proof);
    let one = BigInt::from(1u8);

    let mut wrong = hints.clone();
    wrong.s += &one;
    assert!(check_hints(&params, c_k, h, &bits, &proof, &wrong).is_err());

    let mut wrong = hints.clone();
    wrong.xi += &one;
    assert!(check_hints(&params, c_k, h, &bits, &proof, &wrong).is_err());

    let mut wrong = hints.clone();
    wrong.carries[2][7] += &one;
    assert!(check_hints(&params, c_k, h, &bits, &proof, &wrong).is_err());

    // hints of another statement do not fit
    let mut other_bits = bits.clone();
    other_bits[9] = !other_bits[9];
    assert!(check_hints(&params, c_k, h, &other_bits, &proof, &hints).is_err());
}

#[test]
fn extreme_responses_stay_in_range() {
    // all responses at the top or bottom of the scalar field: the bounds on quotient and carries must still hold
    let (params, c_k, h, bits, mut proof) = sample(128, 6);
    for value in [-ScalarField::from(1u64), ScalarField::from(0u64)] {
        proof.z.iter_mut().for_each(|z| *z = value);
        proof.z_k = value;
        for all_set in [true, false] {
            let bits = vec![all_set; bits.len()];
            let hints = CircuitHints::new(&params, c_k, h, &bits, &proof);
            check_hints(&params, c_k, h, &bits, &proof, &hints).expect("constraints hold");
        }
    }
}

fn decimal(x: BaseField) -> String {
    BigUint::from(x.into_bigint()).to_string()
}

/// Writes the generator constants and known-answer inputs for the Circom verifier into `$LEGENDRE_OUT_DIR`.
///
/// `LEGENDRE_OUT_DIR=<dir> cargo test -p taceo-oprf-core --lib legendre::circuit -- --ignored`
#[test]
#[ignore = "generates files for the Circom circuit"]
fn generate_circuit_files() {
    use std::fmt::Write as _;
    let dir = std::path::PathBuf::from(
        std::env::var("LEGENDRE_OUT_DIR").expect("LEGENDRE_OUT_DIR is set"),
    );

    let params = LegendreParams::new(crate::legendre::params::MAX_BITS);
    let mut out = String::from(
        "pragma circom 2.2.2;\n\n// GENERATED by `generate_circuit_files` in taceo-oprf-core (legendre::circuit). Do not edit.\n\n",
    );
    let ds = BaseField::from_be_bytes_mod_order(b"Legendre OPRF proof");
    writeln!(out, "// Domain separator of the proof transcript, b\"Legendre OPRF proof\".\nfunction LegendreProofDS() {{\n    return {};\n}}\n", decimal(ds)).expect("write");
    writeln!(
        out,
        "// Blinding generator H.\nfunction LegendreGeneratorH() {{\n    return [{}, {}];\n}}\n",
        decimal(params.h.x),
        decimal(params.h.y)
    )
    .expect("write");
    writeln!(out, "// Vector commitment generator G_j.\nfunction LegendreGeneratorG(j) {{\n    var G[{}][2] = [", params.n_bits()).expect("write");
    for (j, g) in params.gens.iter().enumerate() {
        let sep = if j + 1 == params.n_bits() { "" } else { "," };
        writeln!(out, "        [{}, {}]{sep}", decimal(g.x), decimal(g.y)).expect("write");
    }
    out.push_str("    ];\n    return G[j];\n}\n");
    std::fs::write(dir.join("legendre_generators.circom"), out).expect("can write generators");

    for (n_bits, seed) in [(128, 100), (16, 101)] {
        let (params, c_k, h, bits, proof) = sample(n_bits, seed);
        proof.verify(&params, c_k, h, &bits).expect("valid proof");
        let json = circuit_inputs(&params, c_k, h, &bits, &proof)
            .into_iter()
            .map(|(name, values)| {
                let values = values.into_iter().map(decimal).collect::<Vec<_>>();
                let value = if values.len() == 1 && !["s_quotient", "bits", "z"].contains(&name) {
                    serde_json::Value::from(values[0].clone())
                } else {
                    serde_json::Value::from(values)
                };
                (name.to_owned(), value)
            })
            .collect::<serde_json::Map<_, _>>();
        let path = dir.join(format!("legendre_kat_{n_bits}.json"));
        std::fs::write(
            path,
            serde_json::to_string_pretty(&json).expect("serializes"),
        )
        .expect("can write kat");
    }
}
